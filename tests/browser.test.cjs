const { chromium } = require("playwright");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const { pathToFileURL } = require("node:url");
const testUrl = process.env.ATOMIZER_TEST_URL || pathToFileURL(path.join(__dirname, "..", "dist", "index.html")).href;
(async () => {
  const browser = await chromium.launch({ channel: "chrome", headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on("pageerror", e => errors.push(e.message));
  const response = await page.goto(testUrl, { waitUntil: "load" });
  assert.equal(response.status(), 200);
  const state = () => page.locator("#state-badge").textContent();
  const volume = async () => Number(await page.locator("#volume").textContent());
  const expectState = async text => { await page.waitForFunction(t => document.getElementById("state-badge").textContent === t, text, { timeout: 16000 }); };
  const passed = [];
  assert.match(await page.locator("#press-help").textContent(), /Complete setup/);
  await page.locator("#adapter").selectOption("B");
  await page.locator("#attachment").click();
  await page.locator("#confirm").click();
  assert.match(await page.locator("#status").textContent(), /mismatch/);
  passed.push("Wrong adapter is blocked in the UI");
  await page.locator("#attachment").click();
  await page.locator("#adapter").selectOption("A");
  await page.locator("#gasket").check();
  await page.locator("#path-ready").check();
  await page.locator("#attachment").click();
  await page.locator("#confirm").click();
  await expectState("Standby");
  await page.locator("#touch-only").check();
  await expectState("Touch sensing");
  assert.equal(await volume(), 0);
  await page.locator("#touch-only").uncheck();
  passed.push("Touch changes state without pumping");
  await page.locator("#press").focus();
  await page.keyboard.down("Space");
  await page.waitForTimeout(1000);
  assert.ok(await volume() > 0);
  await page.keyboard.up("Space");
  const early = await volume();
  await page.waitForTimeout(700);
  assert.equal(await volume(), early);
  await expectState("Standby");
  passed.push("Keyboard hold and release starts and cancels dispensing");
  await page.locator("#dose").selectOption("30");
  await page.locator(".test-controls summary").click();
  await page.locator("#held-test").check();
  await expectState("Dose complete");
  assert.equal(await volume(), 30);
  await page.waitForTimeout(600);
  assert.equal(await volume(), 30);
  await page.locator("#held-test").uncheck();
  await expectState("Standby");
  passed.push("Target stops flow and a held signal cannot restart");
  await page.locator("#held-test").check();
  await page.waitForTimeout(500);
  await page.locator("#attachment").click();
  await expectState("Detached");
  const interrupted = await volume();
  await page.locator("#attachment").click();
  await page.locator("#confirm").click();
  assert.match(await page.locator("#status").textContent(), /Release/);
  await page.waitForTimeout(400);
  assert.equal(await volume(), interrupted);
  await page.locator("#held-test").uncheck();
  await page.locator("#confirm").click();
  await expectState("Standby");
  passed.push("Reattachment with held input cannot spray or confirm setup");
  await page.locator("#sensor-fault").check();
  await expectState("Fault");
  await page.locator("#sensor-fault").uncheck();
  assert.equal(await state(), "Fault");
  await page.locator("#reset-fault").click();
  await expectState("Setup required");
  await page.locator("#confirm").click();
  passed.push("Sensor faults require clearing, reset and setup");
  await page.locator("#depth").fill("100");
  await page.locator("#speed").selectOption("1.2");
  await page.locator("#over-limit").check();
  await page.locator("#held-test").check();
  await expectState("Fault");
  assert.equal(await volume(), 100);
  passed.push("Hard cap blocks the 120-unit test target");
  await page.locator("#held-test").uncheck();
  await page.locator("#over-limit").uncheck();
  await page.locator("#reset-fault").click();
  await page.locator("#confirm").click();
  await page.locator("#dose").selectOption("90");
  await page.locator("#depth").fill("20");
  await page.locator("#speed").selectOption("0.8");
  await page.locator("#held-test").check();
  await expectState("Fault");
  assert.equal(await page.locator("#elapsed").textContent(), "12.0 s");
  passed.push("Slow dispensing reaches the 12-second timeout");
  await page.locator("#ready-example").click();
  await expectState("Standby");
  assert.equal(await volume(), 0);
  assert.equal(await page.locator("#held-test").isChecked(), false);
  assert.equal(await page.locator("#over-limit").isChecked(), false);
  await page.locator("#press").hover();
  await page.mouse.down();
  await page.waitForTimeout(800);
  assert.ok(await volume() > 0);
  await page.mouse.up();
  await expectState("Standby");
  const stopped = await volume();
  await page.waitForTimeout(300);
  assert.equal(await volume(), stopped);
  passed.push("Ready example clears a fault and mouse hold/release dispenses and stops");
  await page.locator("#depth").fill("55");
  await page.locator("#dose").selectOption("60");
  await page.locator("#speed").selectOption("1");
  const out = path.join(__dirname, "..", "qa");
  fs.mkdirSync(out, { recursive: true });
  await page.locator("#depth").fill("25");
  await page.locator("#press").hover();
  await page.mouse.down();
  await page.waitForTimeout(600);
  assert.match(await page.locator("#scene").getAttribute("class"), /spraying/);
  const narrow = await page.locator(".spray").evaluate(el => el.getBoundingClientRect().width);
  await page.mouse.up();
  await expectState("Standby");
  assert.doesNotMatch(await page.locator("#scene").getAttribute("class"), /spraying/);
  await page.locator("#depth").fill("100");
  await page.locator("#press").hover();
  await page.mouse.down();
  await page.waitForTimeout(600);
  assert.ok(await page.locator(".spray").evaluate(el => el.getBoundingClientRect().width) > narrow);
  assert.match(await page.locator("#spray-feedback").textContent(), /full, wide mist/);
  await page.locator(".experience").screenshot({ path: path.join(out, "spraying.png") });
  await page.mouse.up();
  await expectState("Standby");
  passed.push("Visible spray widens with press depth and disappears on release");
  await page.screenshot({ path: path.join(out, "desktop.png"), fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
  const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
  await mobile.goto(testUrl, { waitUntil: "load" });
  await mobile.locator("#bottle").selectOption("tall");
  await mobile.locator("#ready-example").tap();
  assert.equal(await mobile.locator("#state-badge").textContent(), "Standby");
  assert.equal(await mobile.locator("#adapter").inputValue(), "B");
  assert.equal(await mobile.locator("#tube").inputValue(), "long");
  passed.push("Mobile ready-example button configures matching tall-bottle parts");
  assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
  await mobile.screenshot({ path: path.join(out, "mobile.png"), fullPage: true });
  passed.push("Desktop and mobile layouts have no horizontal overflow");
  assert.deepEqual(errors, []);
  passed.push("No browser JavaScript errors");
  fs.writeFileSync(path.join(out, "browser-results.json"), JSON.stringify({ passed, errors }, null, 2));
  console.log(JSON.stringify({ passed, errors }, null, 2));
  await browser.close();
})().catch(error => { console.error(error); process.exit(1); });

